"""Recompute every headline number in docs/claims.yaml from the saved result files.

    uv run python scripts/check_claims.py              # verify values and that docs quote them
    uv run python scripts/check_claims.py --write-table  # regenerate docs/claims.md
    uv run python scripts/check_claims.py --check-table  # fail if docs/claims.md is stale

A claim passes when the value recomputed from its source file, rounded as declared, equals the
number the documents print, and that printed number appears in every document that cites it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
CLAIMS = ROOT / "docs/claims.yaml"
TABLE = ROOT / "docs/claims.md"
SCALES = {"identity": 1.0, "pct": 100.0, "neg_pct": -100.0}


def select(frame, filters):
    mask = pd.Series(True, index=frame.index)
    for column, wanted in (filters or {}).items():
        mask &= frame[column] == wanted
    return frame[mask]


def compute(source, root):
    path = root / source["file"]
    kind = source["kind"]
    if kind == "json":
        value = json.loads(path.read_text(encoding="utf-8"))
        for key in source["path"]:
            value = value[key]
        return float(value) * SCALES[source.get("transform", "identity")]
    frame = pd.read_csv(path)
    rows = select(frame, source.get("filter"))
    if kind == "csv_count":
        return float(len(rows))
    if len(rows) != 1:
        raise ValueError(f"{source['file']}: filter matched {len(rows)} rows, expected 1")
    return float(rows.iloc[0][source["column"]]) * SCALES[source.get("transform", "identity")]


def display(claim):
    return f"{claim['value']:.{claim['decimals']}f}{claim.get('unit', '')}"


def verify(claims, root):
    problems = []
    for claim in claims:
        try:
            actual = round(compute(claim["source"], root), claim["decimals"])
        except Exception as error:  # report, do not stop at the first failure
            problems.append(f"{claim['id']}: cannot recompute ({error})")
            continue
        if abs(actual - claim["value"]) > 1e-9:
            problems.append(
                f"{claim['id']}: file gives {actual}, claims.yaml says {claim['value']}"
            )
        for doc in claim.get("cited_in", []):
            if not (root / doc).exists():
                problems.append(f"{claim['id']}: cited document {doc} does not exist")
                continue
            text = (root / doc).read_text(encoding="utf-8").replace("−", "-")
            if doc.endswith(".tex"):
                text = text.replace("\\,\\%", "%").replace("\\%", "%").replace("$-$", "-")
            if display(claim) not in text:
                problems.append(f"{claim['id']}: '{display(claim)}' not found in {doc}")
    return problems


def table(claims):
    lines = [
        "# Claim-to-evidence table",
        "",
        "Generated by `scripts/check_claims.py --write-table`; do not edit by hand. Each row's number",
        "is recomputed from the saved file in its source column by the CI check.",
        "",
        "| ID | Statement | Value | Source file | Cited in |",
        "|---|---|---:|---|---|",
    ]
    for claim in claims:
        source = claim["source"]["file"]
        cited = ", ".join(f"[{Path(d).name}](../{d})" for d in claim.get("cited_in", [])) or "none"
        lines.append(
            f"| {claim['id']} | {claim['statement']} | {display(claim)} | "
            f"[`{source}`](../{source}) | {cited} |"
        )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--write-table", action="store_true")
    parser.add_argument("--check-table", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    claims = yaml.safe_load((root / "docs/claims.yaml").read_text(encoding="utf-8"))["claims"]
    ids = [c["id"] for c in claims]
    problems = [f"duplicate id {i}" for i in set(ids) if ids.count(i) > 1]
    problems += verify(claims, root)
    rendered = table(claims)
    target = root / "docs/claims.md"
    if args.write_table:
        target.write_text(rendered, encoding="utf-8", newline="\n")
    elif args.check_table and (
        not target.exists() or target.read_text(encoding="utf-8").replace("\r\n", "\n") != rendered
    ):
        problems.append("docs/claims.md is stale; run --write-table")
    for problem in problems:
        print(problem)
    print(f"{len(claims)} claims checked, {len(problems)} problem(s)")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
